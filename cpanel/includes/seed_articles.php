<?php
declare(strict_types=1);

/**
 * هم‌تراز کردن خلاصه مقالات قدیمی + درج مقاله ویژه در صورت نبودن.
 */
function ensure_featured_psychology_article(PDO $pdo): void
{
    static $done = false;
    if ($done) {
        return;
    }
    $done = true;

    // متن و عنوان هم‌طول برای تراز بصری کارت‌ها در خانه
    $cards = [
        'modiriat-ezterab' => [
            'title' => 'چگونه اضطراب روزمره را مدیریت کنیم؟',
            'excerpt' => 'اضطراب بخشی طبیعی از زندگی است؛ اما با تنفس آگاهانه، نظم روزانه و حمایت تخصصی می‌توان فشار آن را کم کرد — بدون اینکه جای درمان فردی را بگیرد.',
        ],
        'khab-salem' => [
            'title' => 'اهمیت خواب سالم برای آرامش ذهن و سلامت روان',
            'excerpt' => 'خواب کافی پایهٔ تمرکز، خلق پایدار و آرامش ذهن است؛ بی‌خوابی می‌تواند اضطراب را شدیدتر کند — بدون اینکه جای ارزیابی تخصصی را بگیرد.',
        ],
        'mehrbani-ba-khod-va-ezterab' => [
            'title' => 'مهربانی با خود: چطور با اضطراب و صدای منتقد درونی آشتی کنیم؟',
            'excerpt' => 'بر اساس پژوهش‌های تازه روانشناسی، تقویت مهربانی با خود می‌تواند استرس، اضطراب و خلق پایین را کم کند — بدون اینکه جای درمان تخصصی را بگیرد.',
        ],
    ];

    $upd = $pdo->prepare('UPDATE articles SET title=?, excerpt=? WHERE slug=?');
    foreach ($cards as $slug => $row) {
        $upd->execute([$row['title'], $row['excerpt'], $slug]);
    }

    $slug = 'mehrbani-ba-khod-va-ezterab';
    $check = $pdo->prepare('SELECT id FROM articles WHERE slug=? LIMIT 1');
    $check->execute([$slug]);
    if ($check->fetch()) {
        return;
    }

    $authorId = $pdo->query("SELECT id FROM users WHERE role='DOCTOR' ORDER BY created_at ASC LIMIT 1")->fetchColumn();
    if (!$authorId) {
        $authorId = $pdo->query("SELECT id FROM users WHERE role='ADMIN' ORDER BY created_at ASC LIMIT 1")->fetchColumn();
    }
    if (!$authorId) {
        return;
    }

    $title = $cards[$slug]['title'];
    $excerpt = $cards[$slug]['excerpt'];

    $content = <<<'HTML'
<p>خیلی از ما وقتی اشتباه می‌کنیم یا احساس ضعف داریم، با خودمان سخت‌گیرتر از هر کس دیگری حرف می‌زنیم. این صدای تند درونی گاهی به‌اشتباه انگیزه به‌نظر می‌رسد، اما پژوهش‌های تازه روانشناسی نشان می‌دهد که <strong>مهربانی با خود (Self-Compassion)</strong> نه تنبلی است و نه خودخواهی؛ بلکه مهارتی آموختنی برای مراقبت از سلامت روان است.</p>

<h2>مهربانی با خود یعنی چه؟</h2>
<p>کریستین نف، یکی از پژوهشگران شناخته‌شده این حوزه، مهربانی با خود را در سه بخش ساده توضیح می‌دهد:</p>
<ul>
  <li><strong>مهربانی به‌جای قضاوت:</strong> وقتی رنج می‌کشید، با خودتان مثل یک دوست دلسوز حرف بزنید نه مثل یک قاضی سخت‌گیر.</li>
  <li><strong>اشتراک انسانی:</strong> به‌یاد بیاورید که اشتباه کردن، خسته شدن و آسیب‌دیدن بخشی از تجربه انسانی است؛ شما تنها نیستید.</li>
  <li><strong>ذهن‌آگاهی:</strong> احساسات را ببینید و نام بگذارید، بدون اینکه در آن‌ها غرق شوید یا انکارشان کنید.</li>
</ul>

<h2>پژوهش‌های تازه چه می‌گویند؟</h2>
<p>در سال‌های ۲۰۲۵ و ۲۰۲۶، چند مرور نظام‌مند و کارآزمایی بالینی دوباره نشان دادند که مداخلات مبتنی بر مهربانی با خود می‌توانند به کاهش اضطراب، نشانه‌های افسردگی و استرس ادراک‌شده کمک کنند؛ به‌ویژه وقتی تمرین‌ها ساخت‌یافته، کوتاه و قابل‌تکرار باشند.</p>
<p>همچنین یافته‌ها حاکی از آن است که بخش «سخت‌گیری و قضاوت نسبت به خود» اغلب پیوند قوی‌تری با رنج روان‌شناختی دارد. به زبان ساده: گاهی مسیر بهتر، فقط مثبت‌اندیشی نیست؛ بلکه <em>کم کردن خشونت کلامی با خود</em> است.</p>
<p>در اضطراب فراگیر نیز تمرین‌های کوتاه «گفت‌وگوی مهربانانه با خود» توانسته در برخی مطالعات، کنار آمدن با استرس را بهتر کند. البته این تمرین‌ها جایگزین روان‌درمانی تخصصی نیستند، اما می‌توانند مکمل مفیدی باشند.</p>

<h2>یک تمرین کوتاه برای همین امروز</h2>
<p>اگر الان مضطرب یا خسته‌اید، این سه گام را آرام امتحان کنید:</p>
<ol>
  <li><strong>توقف و نام‌گذاری:</strong> بگویید «الان دارم اضطراب/شرم/خستگی را حس می‌کنم.»</li>
  <li><strong>جمله انسانی:</strong> «خیلی‌ها در چنین شرایطی چنین احساسی دارند؛ این نشانهٔ ضعف من نیست.»</li>
  <li><strong>جمله حمایتی:</strong> «الان به حمایت نیاز دارم. می‌توانم یک نفس عمیق بکشم و قدم بعدی‌ام را کوچک بردارم.»</li>
</ol>
<p>اگر ذهنتان فوراً گفت «این مسخره‌ است»، همان را هم با مهربانی ببینید؛ مقاومت، بخشی طبیعی از تغییر است.</p>

<h2>چه زمانی بهتر است کمک تخصصی بگیریم؟</h2>
<p>اگر اضطراب یا خلق پایین چند هفته ادامه داشته، روی کار و روابط اثر گذاشته، یا افکار آسیب‌زا دارید، تمرین‌های خودیاری کافی نیستند. در این حالت مراجعه به روان‌درمانگر یا روانشناس بالینی مسیر درست‌تری است. در بحران جدی، فوراً با اورژانس (۱۱۵) تماس بگیرید.</p>

<p><em>این مطلب جنبه آموزشی دارد و تشخیص یا درمان پزشکی محسوب نمی‌شود. برای دریافت راهنمایی شخصی، از متخصصان مانا کلینیک کمک بگیرید یا از دستیار هوشمند سایت شروع کنید.</em></p>
HTML;

    $pdo->prepare('
      INSERT INTO articles (id, title, slug, content, excerpt, published, published_at, author_id)
      VALUES (?,?,?,?,?,1, DATE_ADD(NOW(), INTERVAL 1 MINUTE), ?)
    ')->execute([
        cuid(),
        $title,
        $slug,
        $content,
        $excerpt,
        $authorId,
    ]);
}
