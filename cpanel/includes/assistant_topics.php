function assistant_topic_question(string $topicId, string $questionId): ?array
{
    foreach (assistant_topic_questions($topicId) as $q) {
        if (($q['id'] ?? '') === $questionId) {
            return $q;
        }
    }

    return null;
}

function assistant_flow_meta(array $answers): array
{
    foreach ($answers as $row) {
        if (($row['question_id'] ?? '') === '_flow') {
            return is_array($row['meta'] ?? null) ? $row['meta'] : [];
        }
    }

    return [];
}

function assistant_flow_meta_set(array $answers, array $meta): array
{
    $found = false;
    foreach ($answers as &$row) {
        if (($row['question_id'] ?? '') === '_flow') {
            $row['meta'] = $meta;
            $found = true;
            break;
        }
    }
    unset($row);
    if (!$found) {
        array_unshift($answers, ['question_id' => '_flow', 'meta' => $meta]);
    }

    return $answers;
}

function assistant_answers_for_matching(array $answers): array
{
    $meta = assistant_flow_meta($answers);
    $out = [];
    // نگه داشتن _flow برای امتیازدهی بر اساس موضوع
    foreach ($answers as $row) {
        if (($row['question_id'] ?? '') === '_flow') {
            $out[] = $row;
        }
    }
    $topicId = (string) ($meta['topic'] ?? '');
    if ($topicId !== '') {
        $topic = assistant_topic_by_id($topicId);
        $tags = $topic['tags'] ?? ['therapy'];
        if (in_array($topicId, ['depression'], true)) {
            $optionId = 'depression';
        } elseif (in_array($topicId, ['couples', 'premarital'], true)) {
            $optionId = 'relationship';
        } elseif (in_array($topicId, ['family', 'child'], true)) {
            $optionId = 'family';
        } elseif (in_array($topicId, ['organizational'], true)) {
            $optionId = 'self';
        } elseif ($topicId === 'individual') {
            $optionId = 'anxiety';
        } else {
            $optionId = 'anxiety';
        }
        $out[] = [
            'question_id' => 'main_concern',
            'option_id' => $optionId,
            'tags_override' => $tags,
        ];
    }
    if (!empty($meta['custom_note'])) {
        $out[] = ['question_id' => 'free_note', 'text' => (string) $meta['custom_note']];
    }
    foreach ($answers as $row) {
        if (($row['question_id'] ?? '') === '_flow') {
            continue;
        }
        $out[] = $row;
    }

    return $out;
}
