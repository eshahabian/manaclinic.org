function daily_quote_for_date(?DateTimeInterface $when = null): string
{
    $lines = daily_quotes_list();
    $n = count($lines);
    if ($n === 0) {
        return '';
    }
    $when = $when ?? new DateTimeImmutable('now');
    $dayOfYear = (int) $when->format('z');

    return $lines[$dayOfYear % $n];
}
