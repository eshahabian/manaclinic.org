function mana_path_companion_lines(string $state, int $restDays): array
{
    if ($state === 'crisis') {
        return [
            'الان مهم‌ترین چیز ایمنی توست. لازم نیست مسیر را ادامه بدهی.',
            'اگر در خطر فوری هستی، با اورژانس تماس بگیر. کلینیک هم اینجاست.',
        ];
    }
    if ($restDays >= 3) {
        return [
            'هر وقت آماده بودی ادامه می‌دیم.',
            'نبودنت شکست نیست. من همین‌جا منتظر می‌مانم.',
